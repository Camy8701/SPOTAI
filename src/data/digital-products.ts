export const getDigitalProductBySlug = (slug: string) =>
  digitalProducts.find((product) => product.slug === slug);

export const resolveDigitalProducts = (slugs: string[]) =>
  slugs
    .map((slug) => getDigitalProductBySlug(slug))
    .filter((product): product is DigitalProduct => Boolean(product));
